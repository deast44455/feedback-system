"""
Модуль для автоматической категоризации отзывов
Определяет категорию отзыва на основе ключевых слов в тексте
"""


def detect_category(text):
    """
    Определяет категорию отзыва на основе ключевых слов
    
    Args:
        text (str): Текст отзыва
    
    Returns:
        str: QUALITY, SERVICE, PRICE, DELIVERY или None (если не удалось определить)
    """
    text_lower = text.lower()
    
    # Ключевые слова для каждой категории
    categories = {
        'QUALITY': [
            'качество', 'продукт', 'товар', 'изделие', 'материал',
            'прочн', 'надежн', 'долговечн', 'брак', 'дефект',
            'сломан', 'испорчен', 'работа', 'функционал', 'характеристик'
        ],
        'SERVICE': [
            'обслуживание', 'персонал', 'сотрудник', 'менеджер', 'консультант',
            'вежлив', 'грубост', 'помощь', 'поддержка', 'общение',
            'отношение', 'сервис', 'обслужива', 'внимание', 'компетентн'
        ],
        'PRICE': [
            'цена', 'стоимость', 'дорого', 'дешево', 'скидка', 'акция',
            'переплата', 'экономи', 'выгодн', 'расход', 'тариф',
            'дорогов', 'ценник', 'стоит', 'рубл', 'деньг'
        ],
        'DELIVERY': [
            'доставка', 'курьер', 'привез', 'получ', 'отправ',
            'задержка', 'опоздал', 'вовремя', 'быстро', 'медленно',
            'упаковка', 'повреж', 'целост', 'срок', 'ожидан'
        ]
    }
    
    # Подсчет совпадений для каждой категории
    category_scores = {}
    for category, keywords in categories.items():
        score = sum(1 for keyword in keywords if keyword in text_lower)
        if score > 0:
            category_scores[category] = score
    
    # Возвращаем категорию с наибольшим количеством совпадений
    if category_scores:
        return max(category_scores, key=category_scores.get)
    
    return None  # Если не удалось определить категорию, вернется OTHER по умолчанию
